std::optional<std::size_t> key_index(std::string_view name) noexcept {
  const auto* const found = std::ranges::find(keys, name, &Key::name);
  if (found == std::end(keys)) return std::nullopt;
  return static_cast<std::size_t>(found - std::begin(keys));
}

std::string_view key_name(std::size_t index) noexcept { return keys[index].name; }

std::string_view key_text(std::size_t index) noexcept { return tr().*keys[index].member; }

